/**
 * Export Report Component - PDF download
 * Quantum Telecom Simulator
 */

import React, { useState } from 'react';
import { Download, FileText, Loader2 } from 'lucide-react';
import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

const ExportReport = ({ kpiData, messages, attacks }) => {
  const [isExporting, setIsExporting] = useState(false);

  const generatePDF = () => {
    setIsExporting(true);

    try {
      const doc = new jsPDF('p', 'mm', 'a4');
      const pageWidth = doc.internal.pageSize.getWidth();

      // Title
      doc.setFontSize(18);
      doc.setTextColor(37, 99, 235);
      doc.text('Quantum Telecom Simulator Report', pageWidth / 2, 20, { align: 'center' });

      doc.setFontSize(10);
      doc.setTextColor(100, 116, 139);
      doc.text(`Generated: ${new Date().toLocaleString()}`, pageWidth / 2, 28, { align: 'center' });

      // KPI Section
      doc.setFontSize(14);
      doc.setTextColor(0, 0, 0);
      doc.text('KPI Summary', 14, 40);

      const kpiData_ = [
        ['Metric', 'Value'],
        ['Security Score', `${kpiData?.security_score || 0}%`],
        ['Messages Sent', `${kpiData?.total_secure_messages || 0}`],
        ['Attacks Detected', `${kpiData?.total_attacks_detected || 0}`],
        ['Key Strength', `${kpiData?.quantum_key_strength || 0} bits`],
        ['Network Availability', `${kpiData?.network_availability || 99.9}%`],
        ['Error Rate', `${((kpiData?.error_rate || 0) * 100).toFixed(1)}%`],
        ['Key Compromised', kpiData?.key_compromised ? 'Yes' : 'No'],
      ];

      autoTable(doc, {
        startY: 45,
        head: [['Metric', 'Value']],
        body: kpiData_.slice(1),
        theme: 'striped',
        headStyles: { fillColor: [59, 130, 246] },
      });

      // Messages Section
      const finalY = doc.lastAutoTable.finalY + 10;
      doc.setFontSize(14);
      doc.text('Message History', 14, finalY);

      const msgData = (messages || []).slice(-10).map(m => [
        m.sender || 'Alice',
        m.message || '',
        m.timestamp || '',
      ]);

      if (msgData.length > 0) {
        autoTable(doc, {
          startY: finalY + 5,
          head: [['Sender', 'Message', 'Time']],
          body: msgData,
          theme: 'striped',
          headStyles: { fillColor: [59, 130, 246] },
        });
      } else {
        doc.setFontSize(10);
        doc.text('No messages recorded.', 14, finalY + 10);
      }

      // Attacks Section
      const attackFinalY = doc.lastAutoTable?.finalY + 10 || finalY + 30;
      doc.setFontSize(14);
      doc.text('Attack Logs', 14, attackFinalY);

      const attackData = (attacks || []).slice(-10).map(a => [
        a.type || 'Unknown',
        a.timestamp ? new Date(a.timestamp).toLocaleString() : '',
        a.detected ? '✅ Detected' : '⚠️ Unknown',
      ]);

      if (attackData.length > 0) {
        autoTable(doc, {
          startY: attackFinalY + 5,
          head: [['Attack Type', 'Time', 'Status']],
          body: attackData,
          theme: 'striped',
          headStyles: { fillColor: [239, 68, 68] },
        });
      } else {
        doc.setFontSize(10);
        doc.text('No attacks recorded.', 14, attackFinalY + 10);
      }

      // Footer
      const footerY = doc.internal.pageSize.getHeight() - 10;
      doc.setFontSize(8);
      doc.setTextColor(156, 163, 175);
      doc.text('Generated by Quantum Telecom Simulator v2.0', pageWidth / 2, footerY, { align: 'center' });

      doc.save('quantum-telecom-report.pdf');
    } catch (error) {
      console.error('Error generating PDF:', error);
      alert('Failed to generate report. Please try again.');
    } finally {
      setIsExporting(false);
    }
  };

  return (
    <button
      onClick={generatePDF}
      disabled={isExporting}
      className="flex items-center gap-2 px-3 py-1.5 bg-green-600 hover:bg-green-700 text-white rounded-lg transition disabled:opacity-50 text-sm"
    >
      {isExporting ? (
        <>
          <Loader2 className="w-4 h-4 animate-spin" />
          Generating...
        </>
      ) : (
        <>
          <Download className="w-4 h-4" />
          Export Report
        </>
      )}
    </button>
  );
};

export default ExportReport;